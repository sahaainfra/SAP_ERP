// ═══════════════════════════════════════════════════════════════════════════
// ERROR TYPES
// ═══════════════════════════════════════════════════════════════════════════

export class PostingError extends Error {
  constructor(
    public code: string,
    public details: Record<string, any>
  ) {
    super(`${code}: ${JSON.stringify(details)}`);
    this.name = 'PostingError';
  }
}

export class InsufficientStockError extends PostingError {
  constructor(details: {
    itemCode: string;
    itemName: string;
    store: number;
    available: number;
    requested: number;
    shortfall: number;
    uom: string;
  }) {
    super('INSUFFICIENT_STOCK', details);
  }
}

export class PeriodClosedError extends PostingError {
  constructor(details: {
    period: string;
    module: string;
    closedAt?: string;
    remedy: string;
  }) {
    super('PERIOD_CLOSED', details);
  }
}

export class VoucherUnbalancedError extends PostingError {
  constructor(details: {
    eventType: string;
    debit: number;
    credit: number;
    difference: number;
    lines: VoucherLineDraft[];
  }) {
    super('VOUCHER_UNBALANCED', details);
  }
}

export class DimensionError extends PostingError {
  constructor(
    code: 'DIMENSION_REQUIRED' | 'DIMENSION_NOT_ALLOWED' | 'DIMENSION_COMBINATION_INVALID' | 'COST_CODE_NOT_POSTABLE',
    details: Record<string, any>
  ) {
    super(code, details);
  }
}
