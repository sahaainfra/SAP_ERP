// ═══════════════════════════════════════════════════════════════════════════
// STOCK MOVEMENT TYPES
// ═══════════════════════════════════════════════════════════════════════════

export type StockMovementType = 
  | 'GRN'                    // Goods Receipt Note (inbound)
  | 'ISSUE'                  // Material issue (outbound)
  | 'TRANSFER_OUT'           // Transfer to another store
  | 'TRANSFER_IN'            // Transfer from another store
  | 'ADJUSTMENT'             // Stock adjustment
  | 'REVERSAL'               // Reversal of a previous movement
  | 'OPENING_BALANCE';       // Initial stock load

export interface StockMovementInput {
  projectId: number;
  storeId: number;
  binId?: number;
  itemId: number;
  batchId?: number;
  movementType: StockMovementType;
  movementDate: Date;
  quantity: number;           // ALWAYS positive; sign derived from type
  uom: string;
  rate?: number;              // Required for inbound; derived for outbound
  source: {
    type: string;
    id: number;
    lineId?: number;
  };
  costDestination?: {
    costCodeId?: number;
    wbsId?: number;
    boqItemId?: number;
    equipmentId?: number;
  };
  reversalOfId?: number;
  allowNegative?: boolean;    // Honoured only if project config permits
}

export interface StockLedgerRow {
  id: number;
  projectId: number;
  storeId: number;
  binId?: number;
  itemId: number;
  batchId?: number;
  movementType: StockMovementType;
  movementDate: string;
  quantity: number;           // Signed
  uom: string;
  rate: number;
  value: number;              // Signed
  balanceQty: number;
  balanceValue: number;
  sourceType: string;
  sourceId: number;
  sourceLineId?: number;
  reversalOfId?: number;
  costCodeId?: number;
  wbsId?: number;
  boqItemId?: number;
  equipmentId?: number;
  createdBy: number;
  createdAt: string;
  prevHash: string;
  rowHash: string;
}

export interface StockPostingResult {
  ledgerId: number;
  balanceQty: number;
  balanceValue: number;
  appliedRate: number;
}

