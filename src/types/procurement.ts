// ─── Indent (Purchase Requisition) ───────────────────────────────────────────

export type IndentType = 'REGULAR' | 'URGENT' | 'EMERGENCY' | 'STOCK_REPLENISH' | 'CAPEX';
export type BudgetStatus = 'WITHIN' | 'EXCEEDED' | 'NO_BUDGET' | 'OVERRIDDEN';
export type IndentStatus = 'DRAFT' | 'PENDING_APPROVAL' | 'APPROVED' | 'REJECTED' | 'CANCELLED' | 'CONVERTED_TO_RFQ';

export interface IndentExtension {
  indentId: number;
  projectId: number;
  wbsId?: number;
  costCodeId?: number;
  indentType: IndentType;
  requiredByDate: string;
  justification?: string;
  budgetCheckedAt?: string;
  budgetStatus?: BudgetStatus;
  budgetAvailable?: number;
  stockCheckedAt?: string;
  sourcePlanId?: number; // dx_resource_plan row
  consolidationGroup?: string;
  isAutoGenerated: boolean;
}

export interface IndentItemExtension {
  indentItemId: number;
  itemId?: number;
  boqItemId?: number;
  wbsId?: number;
  specification?: string;
  makePreference?: string;
  stockOnHand: number;
  stockInTransit: number;
  alreadyOrdered: number;
  theoreticalReq: number; // from Part 13 norms
  netRequired: number;
  lastPurchaseRate?: number;
  lastPurchaseDate?: string;
  budgetRate?: number;
  estimatedValue?: number;
}

export interface IndentCheck {
  checkType: 'STOCK' | 'THEORETICAL' | 'BUDGET' | 'DUPLICATE' | 'LEAD_TIME';
  status: 'PASS' | 'WARN' | 'FAIL';
  message: string;
  details?: any;
}

export interface IndentValidation {
  isValid: boolean;
  checks: IndentCheck[];
  canSubmit: boolean;
  requiresOverride: boolean;
  overrideReason?: string;
}

// ─── RFQ (Request for Quotation) ─────────────────────────────────────────────

export type RfqType = 'OPEN' | 'LIMITED' | 'SINGLE' | 'RATE_CONTRACT';
export type RfqStatus = 'DRAFT' | 'ISSUED' | 'CLOSED' | 'SEALED' | 'OPENED' | 'CANCELLED' | 'AWARDED';
export type VendorResponseStatus = 'INVITED' | 'VIEWED' | 'QUOTED' | 'REGRETTED' | 'NO_RESPONSE';

export interface Rfq {
  id: number;
  rfqNo: string;
  projectId?: number;
  companyId: number;
  rfqType: RfqType;
  title: string;
  scopeSummary?: string;
  issueDate: string;
  dueDatetime: string;
  isSealed: boolean;
  openedAt?: string;
  openedBy?: number[]; // Two users for sealed RFQ
  status: RfqStatus;
  deliveryTerms?: string;
  paymentTerms?: string;
  createdBy: number;
  createdAt: string;
  indentMappings?: RfqIndentMap[];
  vendors?: RfqVendor[];
  quotations?: Quotation[];
  comparative?: Comparative;
}

export interface RfqIndentMap {
  id: number;
  rfqId: number;
  indentItemId: number;
  rfqQty: number;
}

export interface RfqVendor {
  id: number;
  rfqId: number;
  vendorId: number;
  vendorName?: string;
  invitedAt?: string;
  invitedBy?: number;
  responseStatus: VendorResponseStatus;
  portalToken?: string;
  tokenExpiresAt?: string;
  quotationId?: number;
}

// ─── Quotation ───────────────────────────────────────────────────────────────

