// ─── Comparative Statement ───────────────────────────────────────────────────

export type EvaluationBasis = 'L1_ITEMWISE' | 'L1_TOTAL' | 'QCBS' | 'LIFECYCLE';
export type ComparativeStatus = 'DRAFT' | 'PENDING_APPROVAL' | 'APPROVED' | 'REJECTED' | 'NEGOTIATION_IN_PROGRESS';

export interface Comparative {
  id: number;
  csNo: string;
  rfqId: number;
  preparedBy?: number;
  preparedAt?: string;
  evaluationBasis: EvaluationBasis;
  technicalWeight?: number; // for QCBS
  commercialWeight?: number; // for QCBS
  status: ComparativeStatus;
  approvedBy?: number;
  approvedAt?: string;
  negotiationRound: number;
  recommendations?: ComparativeRecommendation[];
  // Matrix data
  vendorMatrix?: VendorComparativeData[];
}

export interface ComparativeRecommendation {
  id: number;
  comparativeId: number;
  rfqIndentMapId: number;
  recommendedVendorId: number;
  recommendedVendorName?: string;
  recommendedQty: number;
  recommendedRate: number;
  isLowest: boolean;
  deviationReason?: string; // MANDATORY when isLowest = false
  savingVsBudget?: number;
  savingVsLastPurchase?: number;
  // Additional fields
  itemName?: string;
  itemCode?: string;
  allQuotes?: VendorQuoteForItem[];
}

export interface VendorComparativeData {
  vendorId: number;
  vendorName: string;
  quotationId: number;
  totalValue: number;
  deliveryDays: number;
  paymentTerms: string;
  vendorScorecard?: number; // from Part 12
  isTechnicallyAccepted: boolean;
  itemQuotes: VendorQuoteForItem[];
}

export interface VendorQuoteForItem {
  rfqIndentMapId: number;
  itemName: string;
  itemCode: string;
  quotedQty: number;
  landedRate: number;
  totalValue: number;
  isLowest: boolean;
  rank: number; // 1, 2, 3...
  lastPurchaseRate?: number;
  budgetRate?: number;
  varianceVsBudget?: number;
  varianceVsLastPurchase?: number;
}

export interface NegotiationRound {
  roundNo: number;
  negotiatedAt: string;
  negotiatedBy: number;
  vendorId: number;
  revisedRates: Array<{
    rfqIndentMapId: number;
    oldRate: number;
    newRate: number;
    saving: number;
  }>;
  notes?: string;
}

