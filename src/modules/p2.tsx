/* ══════════ QUALITY ══════════ */
export function QualityPage() {
  const { s, setS, can, log, notify, user } = useERP();
  const toast = useToast();
  const [tab, setTab] = useState<"all" | "Inspection" | "NCR" | "Cube Test">("all");

  const rows = s.quality.filter((q) => tab === "all" || q.type === tab);
  const failed = s.quality.filter((q) => q.status === "Failed" || (q.type === "NCR" && q.status === "Open"));

  const advance = (q: any) => {
    const next = q.status === "Pending" ? "Passed" : q.status === "Open" ? "Closed" : q.status;
    setS((p) => ({ ...p, quality: p.quality.map((x) => x.id === q.id ? { ...x, status: next } : x) }));
    log("Quality", q.type + " " + next, q.no, `${q.item}`);
    notify("system", `${q.no} marked ${next}`);
    toast("success", `${q.no} → ${next}`);
  };

  return (
    <div className="fade-up">
      <PageHead title="Quality Management" crumbs={["Meridian", "Site Operations", "Quality"]}
        desc="Inspections, NCRs and cube tests with corrective-action tracking. Failed tests raise alerts automatically.">
        <Stat label="Inspections" value={`${s.quality.filter((q) => q.type === "Inspection").length}`} />
        <Stat label="Open NCRs" value={`${s.quality.filter((q) => q.type === "NCR" && q.status === "Open").length}`} tone="warn" />
        <Stat label="Cube pass rate" value={`${Math.round((s.quality.filter((q) => q.type === "Cube Test" && q.status === "Passed").length / Math.max(1, s.quality.filter((q) => q.type === "Cube Test").length)) * 100)}%`} tone="ok" />
        <Stat label="Failed / open" value={`${failed.length}`} tone={failed.length ? "danger" : "ok"} />
      </PageHead>
      <Widget title="Quality Records" subtitle="Failed cube tests trigger mix-design review; NCRs require root cause before closure">
        <div className="mb-3"><Seg value={tab} onChange={setTab} options={[
          { k: "all" as const, l: "All", n: s.quality.length }, { k: "Inspection" as const, l: "Inspections" },
          { k: "NCR" as const, l: "NCR" }, { k: "Cube Test" as const, l: "Cube Tests" },
        ]} /></div>
        <div className="grid lg:grid-cols-2 gap-3">
          {rows.map((q) => (
            <div key={q.id} className={cx("rounded-lg border p-3.5 transition-all hover:-translate-y-[2px] hover:shadow-lift", q.status === "Failed" || (q.type === "NCR" && q.status === "Open") ? "border-danger-500/30 bg-danger-100/20" : "border-line bg-surface")}>
              <div className="flex items-center gap-2 flex-wrap">
                <span className="num text-[12px] font-bold text-brand-700">{q.no}</span>
                <span className="text-[10px] font-bold uppercase tracking-wide bg-canvas border border-line rounded px-1.5 py-0.5 text-ink-500 flex items-center gap-1"><IFlask size={10} /> {q.type}</span>
                <span className="num text-[11px] text-ink-400">{q.project} · {q.date}</span>
                <span className="ml-auto"><Pill value={q.status} pulse={q.status === "Pending" || q.status === "Open"} /></span>
              </div>
              <p className="text-[12.5px] font-semibold text-ink-900 mt-2">{q.item}</p>
              {q.result && <p className="text-[11.5px] text-ink-500 mt-1">{q.result}</p>}
              {(q.status === "Pending" || q.status === "Open") && can("rmc", "edit") || (q.status === "Pending" && can("projects", "edit")) ? (
                <div className="flex justify-end mt-2.5">
                  <Btn sm kind={q.type === "NCR" ? "danger" : "ok"} onClick={() => advance(q)}>
                    {q.type === "NCR" ? "Close with Action" : "Mark Passed"}</Btn>
                </div>) : null}
            </div>))}
        </div>
        {rows.length === 0 && <Empty title="No records in this view" note="Quality records are created from site inspections and RMC batches." />}
      </Widget>
    </div>
  );
}

