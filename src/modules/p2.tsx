const INR = (v: number) => "₹" + v.toLocaleString("en-IN", { maximumFractionDigits: 0 });

/* ══════════ PF MANAGEMENT ══════════ */
export function PFPage() {
  const { s, setS, can, log, notify, user } = useERP();
  const toast = useToast();
  const pending = s.pf.filter((p) => p.status === "Pending");
  const total = s.pf.reduce((a, p) => a + p.empShare + p.erShare, 0);

  const pay = (p: any) => {
    setS((st) => ({ ...st, pf: st.pf.map((x) => x.id === p.id ? { ...x, status: "Paid", paidOn: dStr(0) } : x) }));
    log("Payroll", "PF Remitted", p.pfNo, `${p.emp} · ${p.month} · ${INR(p.empShare + p.erShare)}`);
    notify("hr", `PF remitted for ${p.emp} — ${p.month}`);
    toast("success", `PF remitted — ${p.emp}`);
  };

  const printPF = () => printDocument({
    title: "Monthly PF Register", docNo: "PF-" + dStr(0).replace(/\s/g, ""), date: dStr(0),
    meta: [["Period", s.pf[0]?.month ?? "Current"], ["Establishment", "SAHAA INFRA LTD — MHAPP"], ["Generated By", user.name]],
    cols: [{ label: "Employee" }, { label: "PF No." }, { label: "Month" }, { label: "PF Wage (₹)", align: "right" }, { label: "Employee Share", align: "right" }, { label: "Employer Share", align: "right" }, { label: "Status" }],
    rows: s.pf.map((p) => [p.emp, p.pfNo, p.month, p.wage, p.empShare, p.erShare, p.status]),
    totalsLabel: "Total Contribution (₹)", totals: [total],
    signatures: ["Prepared By", "Accounts Manager"],
    note: "Employee 12% + Employer 12% on PF wage, capped as per EPF Act. Sensitive wage details restricted to HR & Accounts.",
    generatedBy: user.name,
  });

  return (
    <div className="fade-up">
      <PageHead title="PF Management" crumbs={["Meridian", "People", "Provident Fund"]}
        desc="EPF contributions linked to payroll — wage, employee & employer share, remittance tracking.">
        <Stat label="Total contribution" value={INR(total)} />
        <Stat label="Pending remittance" value={`${pending.length}`} tone={pending.length ? "warn" : "ok"} />
        <Stat label="Rate" value="12% + 12%" sub="Employee + Employer" />
        <Btn onClick={printPF}><IPrinter size={13} /> Print Register</Btn>
      </PageHead>
      <Widget title="PF Register" subtitle="Remittance posts a Payment voucher to Accounts on approval">
        <DataTable pageKey="pf" rows={s.pf} cols={[
          { key: "emp", label: "Employee", render: (p) => <span className="text-[12.5px] font-semibold text-ink-900">{p.emp}</span> },
          { key: "pfNo", label: "PF No.", render: (p) => <span className="num text-[11.5px] text-ink-500">{p.pfNo}</span> },
          { key: "month", label: "Month", render: (p) => <span className="text-[12px] text-ink-500">{p.month}</span> },
          { key: "wage", label: "PF Wage", align: "right", sort: (p) => p.wage, render: (p) => <span className="num text-[12px]">{INR(p.wage)}</span> },
          { key: "empShare", label: "Employee", align: "right", sort: (p) => p.empShare, render: (p) => <span className="num text-[12px]">{INR(p.empShare)}</span> },
          { key: "erShare", label: "Employer", align: "right", sort: (p) => p.erShare, render: (p) => <span className="num text-[12px]">{INR(p.erShare)}</span> },
          { key: "status", label: "Status", render: (p) => <Pill value={p.status === "Paid" ? "Completed" : "Pending"} pulse={p.status === "Pending"} />, csv: (p) => p.status },
          { key: "act", label: "", render: (p: any) => p.status === "Pending" && can("payroll", "approve") ? <Btn sm kind="ok" onClick={(e: any) => { e.stopPropagation(); pay(p); }}><ICheck size={11} /> Remit</Btn> : null },
        ] as Col[]} />
      </Widget>
    </div>
  );
}

